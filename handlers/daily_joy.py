@router.callback_query(F.data == "joy:get")
async def cb_joy_get(callback: CallbackQuery):
    task = random.choice(JOY_TASKS)
    await callback.message.edit_text(
        f"☀️ Маленькая радость на сегодня:\n\n{task}",
        reply_markup=back_to_main_kb(),
    )
    await callback.answer()