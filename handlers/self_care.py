@router.callback_query(F.data == "selfcare:menu")
async def cb_selfcare_menu(callback: CallbackQuery):
    await callback.message.edit_text(
        "🌷 Выбери тему — здесь собраны честные и тёплые разговоры не только про "
        "беременность, но и про то, что будет после, и про заботу о себе.",
        reply_markup=selfcare_menu_kb(),
    )
    await callback.answer()


@router.callback_query(F.data.startswith("selfcare:topic:"))
async def cb_selfcare_topic(callback: CallbackQuery):
    key = callback.data.split(":")[2]
    title, text = TOPICS[key]

    await callback.message.edit_text(
        f"{title}\n\n{text}", reply_markup=back_to_main_kb()
    )
    await callback.answer()